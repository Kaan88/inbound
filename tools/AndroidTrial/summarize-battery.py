"""Battery trial summariser (run-battery.sh).
  row <dir> <label> <kind> <size>   one TSV row for rows.tsv
  summary <dir>                     summary.md from rows.tsv, the batterystats files and uids.txt
"""
import json, os, re, sys

STEP_MAH = 4.357
GIB = 1024 ** 3

HEAD = ["label", "case", "bytes", "dl_seconds", "MiB_per_s", "window_s", "cc_start_uAh", "cc_end_uAh", "mAh", "mean_mV",
        "mWh", "temp_start_C", "temp_max_C", "temp_end_C", "level_start", "level_end"]


def read_tsv(path):
    with open(path) as f:
        return [l.rstrip("\n").split("\t") for l in f if l.strip()]


def window(d, label):
    ev = {}
    for k, v in read_tsv(os.path.join(d, label + ".events.tsv")):
        ev.setdefault(k, int(v))
    s = [list(map(int, r)) for r in read_tsv(os.path.join(d, label + ".samples.tsv"))]
    return ev, s


def row(d, label, kind, size):
    ev, s = window(d, label)
    w = [r for r in s if ev["window_start"] <= r[0] <= ev["window_end"]]
    first, last = w[0], w[-1]
    secs = (last[0] - first[0]) / 1000
    mah = (first[1] - last[1]) / 1000
    mv = sum(r[2] for r in w) / len(w)
    mwh = mah * mv / 1000
    temps = [r[3] / 10 for r in w]
    nbytes, dl = 0, ""
    if kind.startswith("app"):
        try:
            j = json.load(open(os.path.join(d, label + ".json")))
            nbytes, dl = j.get("bytes", 0), j.get("wallSeconds", "")
        except Exception:
            pass
    elif kind == "browser":
        if "done" in ev and "first_bytes" in ev:
            nbytes, dl = int(size), (ev["done"] - ev["first_bytes"]) / 1000   # size = bytes the browser was asked for; rx check is in the events
    mibs = (nbytes / 1048576 / float(dl)) if dl not in ("", 0) and nbytes else ""
    vals = [label, kind, nbytes, f"{float(dl):.1f}" if dl != "" else "", f"{mibs:.2f}" if mibs != "" else "", f"{secs:.1f}",
            first[1], last[1], f"{mah:.3f}", f"{mv:.0f}", f"{mwh:.3f}", f"{temps[0]:.1f}", f"{max(temps):.1f}", f"{temps[-1]:.1f}",
            first[4], last[4]]
    print("\t".join(map(str, vals)))


def power_lines(path, uids):
    """Raw 'Estimated power use (mAh)' lines for the uids and for screen/wifi."""
    out, on = [], False
    for l in open(path, errors="replace"):
        if "Estimated power use (mAh)" in l:
            on = True
            continue
        if on:
            if not l.strip() or (not l.startswith("    ") and not l.startswith("  ")):
                if out:
                    break
                continue
            t = l.strip()
            if re.match(r"(Screen|Wifi|Idle|Cell standby|Phone calls|Bluetooth|Unaccounted|Over-counted)\b", t) or any(
                    re.match(rf"Uid {re.escape(u)}\b", t) for u in uids.values()):
                out.append(t)
    return out


def summary(d):
    rows = [dict(zip(HEAD, r)) for r in read_tsv(os.path.join(d, "rows.tsv"))]
    uids = {}
    up = os.path.join(d, "uids.txt")
    if os.path.exists(up):
        for l in open(up):
            m = re.match(r"package:(\S+)\s+uid:(\d+)", l.strip())
            if m:
                uid = int(m.group(2))
                uids[m.group(1)] = f"u0a{uid - 10000}" if uid >= 10000 else f"{uid}"
    idle = [r for r in rows if r["case"] == "idle"]
    rate = lambda r: float(r["mAh"]) / float(r["window_s"])           # mAh/s
    rate_w = lambda r: float(r["mWh"]) / float(r["window_s"]) * 3600  # mW
    L = ["# Battery trial summary (generated by tools/AndroidTrial/summarize-battery.py)", "",
         f"Charge counter resolution: one step is about {STEP_MAH} mAh. Windows start and end on a counter step, so each window's mAh is "
         f"quantised; the error per window is about one step at worst (about {STEP_MAH:.1f} mAh), i.e. up to ~{STEP_MAH/12:.2f} mAh per GiB "
         f"for a 12 GiB run (about {STEP_MAH/12*3.9:.1f} mWh per GiB at 3.9 V). MiB/s = 2^20 bytes per second.", "",
         "## Idle (screen on, launcher, brightness 1)", "", "| label | window s | mAh | mAh/s | mW |", "|---|---|---|---|---|"]
    for r in idle:
        L.append(f"| {r['label']} | {r['window_s']} | {r['mAh']} | {rate(r):.5f} | {rate_w(r):.0f} |")
    if idle:
        m = sum(map(rate, idle)) / len(idle)
        mw = sum(map(rate_w, idle)) / len(idle)
        L.append(f"| mean | | | {m:.5f} | {mw:.0f} |")
    else:
        m = mw = 0
    L += ["", "## Download runs: net of idle", "",
          "net = window - idle rate x window seconds. Baselines: mean of the idle windows, and each idle window alone (min/max over those).", "",
          "| label | case | s dl | MiB/s | window s | window mAh | window mWh | net mAh (mean idle) | net mWh | net mAh/GiB | net mWh/GiB | mAh/GiB range (idle min..max) | +/- GiB quant. (mAh) |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["case"] == "idle":
            continue
        ws, mah, mwh = float(r["window_s"]), float(r["mAh"]), float(r["mWh"])
        gib = int(r["bytes"]) / GIB if int(r["bytes"]) else 12
        nm = mah - m * ws
        nw = mwh - mw / 3600 * ws
        rng = [(mah - rate(i) * ws) / gib for i in idle] or [nm / gib]
        L.append(f"| {r['label']} | {r['case']} | {r['dl_seconds']} | {r['MiB_per_s']} | {r['window_s']} | {r['mAh']} | {r['mWh']} | {nm:.2f} | {nw:.2f} | "
                 f"{nm/gib:.3f} | {nw/gib:.3f} | {min(rng):.3f} .. {max(rng):.3f} | {STEP_MAH/gib:.2f} |")
    L += ["", "## OS-modelled power estimates (batterystats 'Estimated power use (mAh)', quoted raw; a model, not a measurement)", ""]
    if uids:
        L.append("uids: " + ", ".join(f"{k}={v}" for k, v in uids.items()))
        L.append("")
    for r in rows:
        p = os.path.join(d, r["label"] + ".batterystats.txt")
        if os.path.exists(p):
            L.append(f"### {r['label']}")
            L.append("```")
            L += power_lines(p, uids) or ["(no matching lines)"]
            L.append("```")
    open(os.path.join(d, "summary.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    if sys.argv[1] == "row":
        row(*sys.argv[2:6])
    else:
        summary(sys.argv[2])
